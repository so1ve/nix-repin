import * as fs from "node:fs/promises";
import * as path from "node:path";

import { runCommand } from "./command.ts";
import { isNotFound } from "./files.ts";

export const HEADER = "# This file is generated by nix-repin. Do not edit.\n\n";

export interface PrefetchResult {
  hash: string;
  storePath: string;
}

export interface GitSource extends PrefetchResult {
  rev: string;
  /**
   * Commit date in YYYY-MM-DD format.
   */
  date: string;
}

export const string = (value: string): string =>
  JSON.stringify(value).replaceAll("${", "\\${");

export async function prefetch(
  url: string,
  { unpack = false, name }: { unpack?: boolean; name?: string } = {},
): Promise<PrefetchResult> {
  const output = await runCommand("nix", [
    "store",
    "prefetch-file",
    "--json",
    ...(unpack ? ["--unpack"] : []),
    ...(name ? ["--name", name] : []),
    url,
  ]);
  const { hash, storePath } = JSON.parse(output) as PrefetchResult;

  return { hash, storePath };
}

export const prefetchGit = async (
  url: string,
  revision: string,
): Promise<string> => (await prefetchGitSource(url, revision)).hash;

/**
 * Fetch a Git checkout without submodules and return its commit and store path.
 */
export async function prefetchGitSource(
  url: string,
  revision: string,
): Promise<GitSource> {
  const output = await runCommand("nix-prefetch-git", [
    "--quiet",
    "--url",
    url,
    "--rev",
    revision,
  ]);

  const { rev, date, hash, path } = JSON.parse(output) as {
    rev: string;
    date: string;
    hash: string;
    path: string;
  };

  return { rev, date: date.slice(0, 10), hash, storePath: path };
}

/**
 * Walk up from `from` to the repository flake that contains the package.
 */
export async function findFlakeRoot(from: string): Promise<string> {
  let directory = path.resolve(from);
  while (true) {
    try {
      if ((await fs.stat(path.join(directory, "flake.nix"))).isFile()) {
        return directory;
      }
    } catch (error) {
      if (!isNotFound(error)) {
        throw error;
      }
    }

    const parent = path.dirname(directory);
    if (parent === directory) {
      throw new Error(`no flake.nix found at or above ${from}`);
    }
    directory = parent;
  }
}

/**
 * Build an attribute of the repository flake's `nixpkgs` input for the current
 * system and return the store path of its `out` output.
 */
export async function buildNixpkgsPackage(
  packageDirectory: string,
  attribute: string,
): Promise<string> {
  const root = await findFlakeRoot(packageDirectory);
  const expression = `let
  flake = builtins.getFlake ${string(`path:${root}`)};
  pkgs = flake.inputs.nixpkgs.legacyPackages.\${builtins.currentSystem};
in
pkgs.${attribute}`;

  const output = await runCommand("nix", [
    "build",
    "--expr",
    expression,
    "--impure",
    "--json",
    "--no-link",
  ]);

  const [result] = JSON.parse(output) as {
    outputs: Record<string, string>;
  }[];

  return result.outputs.out;
}

async function ensureFileExists(file: string): Promise<string | undefined> {
  const resolved = path.resolve(file);
  try {
    const stat = await fs.stat(resolved);
    if (!stat.isFile()) {
      const error = new Error(
        `EISDIR: illegal operation on a directory, read '${resolved}'`,
      );
      (error as NodeJS.ErrnoException).code = "EISDIR";

      throw error;
    }

    return resolved;
  } catch (error) {
    if (isNotFound(error)) {
      return undefined;
    }

    throw error;
  }
}

const evalImportedExpr = (resolved: string): string => `let
  imported = import (builtins.toPath ${string(resolved)});
  call =
    system:
    if builtins.isFunction imported then
      imported (
        builtins.mapAttrs (
          name: _:
          if name == "stdenv" then { hostPlatform.system = system; } else x: x
        ) (builtins.functionArgs imported)
      )
    else
      imported;`;

/**
 * Evaluate selected top-level attributes of a generated Nix file by stubbing
 * fetcher arguments as identity functions. Returns `undefined` when the file
 * does not exist.
 */
export async function evalSource(
  file: string,
  attributes: string[],
  system = "x86_64-linux",
): Promise<Record<string, unknown> | undefined> {
  const resolved = await ensureFileExists(file);
  if (resolved === undefined) {
    return undefined;
  }

  const keys = attributes.map(string).join(" ");
  const expression = `${evalImportedExpr(resolved)}
  value = call ${string(system)};
  present = builtins.filter (name: builtins.hasAttr name value) [ ${keys} ];
in
builtins.listToAttrs (
  map (name: {
    inherit name;
    value =
      let
        evaluated = builtins.tryEval (builtins.toJSON value.\${name});
      in
      if evaluated.success then builtins.fromJSON evaluated.value else null;
  }) present
)`;

  const output = await runCommand("nix", [
    "eval",
    "--impure",
    "--json",
    "--expr",
    expression,
  ]);

  return JSON.parse(output) as Record<string, unknown>;
}

/**
 * Evaluate a generated Nix file for each requested Nix system, stubbing fetcher
 * arguments as identity functions. Unsupported systems yield `null`.
 */
export async function evalSources(
  file: string,
  systems: string[],
): Promise<Record<string, Record<string, unknown> | null> | undefined> {
  const resolved = await ensureFileExists(file);
  if (resolved === undefined) {
    return undefined;
  }

  const entries = systems
    .map(
      (system) => `  ${string(system)} =
    let
      evaluated = builtins.tryEval (builtins.toJSON (call ${string(system)}));
    in
    if evaluated.success then builtins.fromJSON evaluated.value else null;`,
    )
    .join("\n");

  const expression = `${evalImportedExpr(resolved)}
in
{
${entries}
}`;

  const output = await runCommand("nix", [
    "eval",
    "--impure",
    "--json",
    "--expr",
    expression,
  ]);

  return JSON.parse(output) as Record<string, Record<string, unknown> | null>;
}

export function renderSource(
  inputs: string[],
  attributes: Record<string, string>,
  body: string,
): string {
  const parameters = `{ ${inputs.join(", ")} }:`;
  const bindings = Object.entries(attributes)
    .map(([name, value]) => `  ${name} = ${string(value)};`)
    .join("\n");
  const exported = [...Object.keys(attributes), "src"].join(" ");

  return `${HEADER}${parameters}

let
${bindings}
${body}
in
{
  inherit ${exported};
}
`;
}

/**
 * Render a tar.gz source using a known unpacked hash, without downloading it.
 */
export const renderArchive = (
  source: { url: string; hash: string },
  attributes: Record<string, string>,
): string =>
  renderSource(
    ["fetchzip"],
    attributes,
    `  src = fetchzip {
    url = ${string(source.url)};
    hash = ${string(source.hash)};
    extension = "tar.gz";
  };`,
  );
