import * as path from "@std/path";

import { runCommand } from "./command.ts";

export const HEADER = "# This file is generated by nix-repin. Do not edit.\n\n";

export interface PrefetchResult {
  hash: string;
  storePath: string;
}

export interface GitSource extends PrefetchResult {
  rev: string;
  /** Commit date in YYYY-MM-DD format. */
  date: string;
}

export function string(value: string): string {
  return JSON.stringify(value).replaceAll("${", "\\${");
}

export async function prefetch(
  url: string,
  { unpack = false, name }: { unpack?: boolean; name?: string } = {},
): Promise<PrefetchResult> {
  const output = await runCommand("nix", [
    "store",
    "prefetch-file",
    "--json",
    ...(unpack ? ["--unpack"] : []),
    ...(name ? ["--name", name] : []),
    url,
  ]);
  const { hash, storePath } = JSON.parse(output) as PrefetchResult;

  return { hash, storePath };
}

export async function prefetchGit(
  url: string,
  revision: string,
): Promise<string> {
  return (await prefetchGitSource(url, revision)).hash;
}

/** Fetch a Git checkout without submodules and return its commit and store path. */
export async function prefetchGitSource(
  url: string,
  revision: string,
): Promise<GitSource> {
  const output = await runCommand("nix-prefetch-git", [
    "--quiet",
    "--url",
    url,
    "--rev",
    revision,
  ]);

  const { rev, date, hash, path } = JSON.parse(output) as {
    rev: string;
    date: string;
    hash: string;
    path: string;
  };
  return { rev, date: date.slice(0, 10), hash, storePath: path };
}

/** Walk up from `from` to the repository flake that contains the package. */
export async function findFlakeRoot(from: string): Promise<string> {
  let directory = path.resolve(from);
  while (true) {
    try {
      if ((await Deno.stat(path.join(directory, "flake.nix"))).isFile) {
        return directory;
      }
    } catch (error) {
      if (!(error instanceof Deno.errors.NotFound)) {
        throw error;
      }
    }

    const parent = path.dirname(directory);
    if (parent === directory) {
      throw new Error(`no flake.nix found at or above ${from}`);
    }
    directory = parent;
  }
}

/**
 * Build an attribute of the repository flake's `nixpkgs` input for the current
 * system and return the store path of its `out` output.
 */
export async function buildNixpkgsPackage(
  packageDirectory: string,
  attribute: string,
): Promise<string> {
  const root = await findFlakeRoot(packageDirectory);
  const expression = `let
  flake = builtins.getFlake ${string(`path:${root}`)};
  pkgs = flake.inputs.nixpkgs.legacyPackages.\${builtins.currentSystem};
in
pkgs.${attribute}`;

  const output = await runCommand("nix", [
    "build",
    "--expr",
    expression,
    "--impure",
    "--json",
    "--no-link",
  ]);

  const [result] = JSON.parse(output) as {
    outputs: Record<string, string>;
  }[];

  return result.outputs.out;
}

export function renderSource(
  inputs: string[],
  attributes: Record<string, string>,
  body: string,
): string {
  const parameters = `{ ${inputs.join(", ")} }:`;
  const bindings = Object.entries(attributes)
    .map(([name, value]) => `  ${name} = ${string(value)};`)
    .join("\n");
  const exported = [...Object.keys(attributes), "src"].join(" ");

  return `${HEADER}${parameters}

let
${bindings}
${body}
in
{
  inherit ${exported};
}
`;
}

/** Render a tar.gz source using a known unpacked hash, without downloading it. */
export function renderArchive(
  source: { url: string; hash: string },
  attributes: Record<string, string>,
): string {
  return renderSource(
    ["fetchzip"],
    attributes,
    `  src = fetchzip {
    url = ${string(source.url)};
    hash = ${string(source.hash)};
    extension = "tar.gz";
  };`,
  );
}
